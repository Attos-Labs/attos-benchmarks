#!/usr/bin/env python3
"""Render README.md from a raw results file produced by run.sh. Every number comes from RESULT lines."""
import re, sys, shlex
raw = open(sys.argv[1]).read().splitlines()
R = []
for l in raw:
    if l.startswith("RESULT "):
        d = {}
        for tok in shlex.split(l[7:]):
            if "=" in tok:
                k, v = tok.split("=", 1); d[k] = v
        R.append(d)
def sel(kind, **kw):
    return [r for r in R if r.get("kind") == kind and all(r.get(k) == v for k, v in kw.items())]
def one(kind, **kw):
    x = sel(kind, **kw); return x[-1] if x else {}
host = [l for l in raw if l.startswith(("Linux", "model name", "cores=", "Mem:", "go version", "Redis server", "# attos-go"))]
ds = [r for r in R if r.get("kind") == "dataset"]
ds = ds[-1] if ds else {}
if not ds: ds = {"n": "0", "key_bytes": "1", "val_bytes": "1", "raw_bytes": "0"}
n = int(one("env").get("n", 0) or 0)
mb = lambda kb: f"{int(kb)/1024:,.0f} MB" if kb not in (None, "", "-1") else "n/a"
def lat(t, scen):
    return one("latency", scen=scen) if False else None
# latency lines are not tagged with target; recover by walking the raw order
cur = None; LAT = {}; RSS = {}
for r in R:
    if r.get("kind") == "env": cur = r["target"]
    if r.get("kind") == "latency": LAT[(cur, r["scen"])] = r
    if r.get("kind") == "rss": RSS[(cur, r["phase"])] = r
us = lambda ns: f"{int(ns)/1000:,.2f} µs"
print("# High-cardinality benchmark results\n")
print("Generated by `highcard/run.sh` from the raw log named below; no number here is typed by hand.\n")
print("## Test environment\n")
print("```"); [print(h) for h in host]; print("```\n")
if ds:
    print(f"- Keys: **{int(ds['n']):,}** unique, 16–32 B (avg {int(ds['key_bytes'])/int(ds['n']):.1f} B); values 8–32 B (avg {int(ds['val_bytes'])/int(ds['n']):.1f} B)")
    print(f"- Raw payload (keys+values): **{mb(int(ds['raw_bytes'])/1024)}**; Attos file on disk: **{mb(int(ds['attos_file_bytes'])/1024)}**")
print("- Workload: single reader goroutine/thread, uniform random keys, **95% hit / 5% miss**, every hit value verified byte-for-byte (`bad` column must be 0)")
print("- Each target runs in a fresh process. Latency = one lookup timed with `time.Now`; Redis uses unpipelined GET over a unix socket (round trip incl. kernel).\n")
PRETTY = {"lean4": "Attos lean-4B*", "lean8": "Attos lean-8B*", "lz4": "Attos LZ4 b8*", "lz4b1": "Attos LZ4 b1*", "lz4b4": "Attos LZ4 b4*", "lz4b8": "Attos LZ4 b8*", "lz4b16": "Attos LZ4 b16*", "lean4lz4b8": "Attos lean-4B+LZ4*", "lean8lz4b8": "Attos lean-8B+LZ4*"}
seen = []
for r in R:
    if r.get("kind") == "env" and r["target"] not in seen: seen.append(r["target"])
def label(t):
    if t == "attos": return "Attos (Go SDK, mmap)"
    if t == "map": return "Go `map[string]string`"
    if t == "redis": return "Redis"
    if t == "lmdb": return "LMDB"
    if t == "rocksdb": return "RocksDB"
    return PRETTY.get(t[6:], t)
T = [(t, label(t)) for t in seen]
DSV = {r.get("variant", "plain"): r for r in R if r.get("kind") == "dataset"}
print("## Results\n")
print("| Metric | " + " | ".join(n for _, n in T) + " |\n|---|" + "---|" * len(T))
def row(name, f):
    print(f"| {name} | " + " | ".join(f(t) for t, _ in T) + " |")
def g(d, k, fmt=lambda x: x):
    return fmt(d[k]) if d and k in d else "not run"
row("Total RSS after load (process)", lambda t: g(RSS.get((t, "loaded")), "vmrss_kb", mb))
row("&nbsp;&nbsp;of which anonymous (heap)", lambda t: g(RSS.get((t, "loaded")), "rss_anon_kb", mb))
row("&nbsp;&nbsp;of which file-backed (mmap)", lambda t: g(RSS.get((t, "loaded")), "rss_file_kb", mb))
row("Total RSS after workload (steady state)", lambda t: g(RSS.get((t, "after_quiet")), "vmrss_kb", mb))
row("Total RSS after GC-churn phase", lambda t: g(RSS.get((t, "after_churn")), "vmrss_kb", mb))
for sc, nm in (("quiet", "no allocation churn"), ("churn", "with ~256 MB/s allocation churn")):
    row(f"P50 lookup ({nm})", lambda t, sc=sc: g(LAT.get((t, sc)), "p50_ns", us))
    row(f"P99 lookup ({nm})", lambda t, sc=sc: g(LAT.get((t, sc)), "p99_ns", us))
    row(f"**P99.9 lookup** ({nm})", lambda t, sc=sc: g(LAT.get((t, sc)), "p999_ns", us))
    row(f"Max lookup ({nm})", lambda t, sc=sc: g(LAT.get((t, sc)), "max_ns", us))
    row(f"GC cycles / max pause ({nm})", lambda t, sc=sc: (f"{LAT[(t, sc)]['gc_cycles']} / {LAT[(t, sc)]['gc_pause_max_us']} µs" if (t, sc) in LAT and t != "redis" else ("n/a (no managed heap in server)" if t == "redis" and (t, sc) in LAT else "not run")))
    if sc == "quiet": row("Heap allocations during timed lookups", lambda t: "n/a (client-side only)" if t == "redis" else g(LAT.get((t, "quiet")), "mallocs"))
    row(f"Lookups / errors ({nm})", lambda t, sc=sc: (f"{int(LAT[(t, sc)]['lookups']):,} / {LAT[(t, sc)]['bad']}" if (t, sc) in LAT else "not run"))
ld = one("load", target="attos"); lm = one("load", target="map")
rs = one("redis_restart"); ri = one("redis_ingest"); rr = one("redis_rdb")
row("On-disk size", lambda t: (mb(int(one("load", target=t)["file_bytes"])/1024) if t.startswith("attos") else (mb(int(one("load", target=t)["on_disk_bytes"])/1024) if t in ("lmdb", "rocksdb") else "1 file, " + mb(int(ds["raw_bytes"])/1024) + " raw (kv.bin)" if t == "map" else (mb(int(rr["bytes"])/1024) + " RDB" if rr else "n/a"))))
def cold(t):
    if t.startswith("attos"):
        d = one("load", target=t)
        return f"open + first lookup **{d['cold_open_first_lookup_ms']} ms** (re-open while serving: {d['reopen_first_lookup_ms']} ms)" if d else "not run"
    if t == "map":
        return f"rebuild from file **{float(lm['load_from_file_ms']):,.0f} ms**"
    if t in ("lmdb", "rocksdb"):
        d = one("load", target=t); b = one("store_build", target=t)
        return f"open **{float(d['open_ms']):,.1f} ms**" + (f" (one-time build {float(b['build_s']):,.0f} s)" if b else "") if d else "not run"
    if t == "redis":
        return f"restart from RDB **{float(rs['seconds'])*1000:,.0f} ms** (initial ingest {float(ri['seconds'])*1000:,.0f} ms)" if rs else "not run"
row("Cold start / reload", cold)
ri_ = [r for r in R if r.get("kind") == "redis_info"]
if ri_:
    print("\nRedis `INFO memory`: " + ", ".join(f"{k}={v}" for r in ri_ for k, v in r.items() if k != "kind"))
print("\n## Notes and caveats (read before quoting)\n")
print("- *Attos lean-4B and LZ4 are optional compile modes that trade lookup speed for smaller files/RAM; lean stores a 4-byte key fingerprint, so a miss can in principle return a wrong hit (the `errors` row counts any).")
print("- Cold start for Attos is measured with the file in the OS page cache (no root to drop caches); a first-ever read from a cold disk is slower.")
print("- Attos RSS counts file-backed mapped pages that the process has touched; they are shared page cache and reclaimable, unlike heap. Both numbers are shown.")
print("- The Go map is loaded from the same raw `kv.bin` file, pre-sized to N entries (the best case for the map).")
print("- Redis latency includes a loopback round trip, so it is not a like-for-like in-process comparison; pipelining would change it.")
print("- The churn phase is a synthetic allocator (64 KB every 0.25 ms; runs at least 20 s, so its lookup count exceeds the quiet phase) to expose GC interaction with a large live heap; real services differ.")
print(f"\nRaw log: `{sys.argv[1]}`")
